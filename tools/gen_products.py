def money(v):
    return int(round(v / 10.0) * 10)


def build():
    products = []
    pid = 0
    for cat in CATS:
        cid = cat["id"]
        feats = FEATURES[cid]
        uses = USES[cid]
        specs_pool = SPECS[cid]
        kinds = cat["kinds"]
        for i in range(100):
            base, pmin, pmax, units = kinds[i % len(kinds)]
            brand = cat["brands"][(i // len(kinds) + i) % len(cat["brands"])]
            series = cat["series"][(i * 3 + i // len(kinds)) % len(cat["series"])]
            unit = units[i % len(units)]
            name = "%s %s %s, %s" % (base, brand, series, unit)
            price = money(pmin + (pmax - pmin) * ((i * 37 % 100) / 100.0))
            old_price = money(price * (1.1 + ((i * 13) % 25) / 100.0)) if i % 3 != 0 else 0
            rating = round(3.8 + ((i * 17) % 13) / 10.0, 1)
            if rating > 5:
                rating = 5.0
            rc = 8 + (i * 29) % 340
            sold = 40 + (i * 97) % 8000
            feat = feats[i % len(feats)]
            feat2 = feats[(i + 2) % len(feats)]
            use = uses[i % len(uses)]
            desc = ("%s %s %s — это %s. Модель %s: %s. Хорошо подходит для %s."
                    % (base, brand, series, feat, unit, feat2, use))
            specs = {}
            for key, vals in specs_pool:
                specs[key] = vals[(i + len(key)) % len(vals)]
            specs["Артикул"] = "LV-%05d" % (pid + 1)
            n_rev = 3 + (i * 7) % 3
            reviews = []
            for r in range(n_rev):
                rr = 5 if r < n_rev - 1 else (4 if i % 4 else 3)
                pool = REVIEW_TEXT["pos"] if rr >= 4 else REVIEW_TEXT["mid"]
                if i % 11 == 0 and r == 0:
                    rr = 2
                    pool = REVIEW_TEXT["neg"]
                text = pool[(i + r * 5) % len(pool)]
                back = (i * 13 + r * 41 + 3) % 330
                day = BASE_DATE - timedelta(days=back)
                reviews.append({
                    "author": AUTHORS[(i * 5 + r * 7) % len(AUTHORS)],
                    "rating": rr,
                    "date": day.isoformat(),
                    "text": text,
                })
            reviews.sort(key=lambda x: x["date"], reverse=True)
            products.append({
                "id": pid + 1,
                "cat": cid,
                "name": name,
                "price": price,
                "oldPrice": old_price,
                "rating": rating,
                "reviews": rc,
                "sold": sold,
                "seller": SELLERS[(i * 3) % len(SELLERS)],
                "delivery": 1 + (i % 4),
                "free": i % 2 == 0,
                "stock": 3 + (i * 11) % 60,
                "desc": desc,
                "specs": specs,
                "revs": reviews,
            })
            pid += 1

    cats = [{"id": c["id"], "name": c["name"], "icon": c["icon"], "color": c["color"]} for c in CATS]
    return {
        "meta": {"version": 1, "count": len(products), "currency": "RUB", "shop": "Лавка"},
        "categories": cats,
        "products": products,
    }


